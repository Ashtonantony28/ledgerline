def q(sheet: str, cell: str) -> str:
    """Absolute, sheet-qualified reference: 'Sheet'!$C$5."""
    col = "".join(ch for ch in cell if ch.isalpha())
    row = "".join(ch for ch in cell if ch.isdigit())
    return f"'{sheet}'!${col}${row}"


def rng(sheet: str, col: str, r1: int, r2: int, abs_col: bool = True) -> str:
    d = "$" if abs_col else ""
    return f"'{sheet}'!{d}{col}${r1}:{d}{col}${r2}"


